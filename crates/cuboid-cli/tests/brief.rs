//! `cuboid-cli brief` on a project library made in the test.

mod common;

use std::fs;

use common::{cli, cli_in, code, names, path_arg, project, stderr, stdout};
use cuboid_library::{
    BRIEF_FILE, Brief, INDEX_FILE, Library, NameCase, Naming, PROJECT_DIR, Scope,
};

fn brief() -> Brief {
    Brief {
        project_name: "Ink Wars".to_owned(),
        mc_version: "1.21.6".to_owned(),
        style_tags: vec!["pixel".to_owned()],
        goal: "Splat weapons".to_owned(),
        namespace: "splatcraft".to_owned(),
        texel_density: Some(16.0),
        texture_size: Some(32),
        palette: vec![[200, 20, 20]],
        naming: Naming {
            case: NameCase::Snake,
            prefix: String::new(),
        },
        rules: vec!["Keep it blocky".to_owned()],
        ..Brief::default()
    }
}

/// The position of each key in the text, which must grow in the order given.
fn in_order(text: &str, keys: &[&str]) {
    let mut last = 0;
    for key in keys {
        let at = text
            .find(&format!("\n  \"{key}\":"))
            .unwrap_or_else(|| panic!("no top-level key {key} in {text}"));
        assert!(at > last, "{key} is out of order");
        last = at;
    }
}

#[test]
fn json_is_the_default_with_the_documented_keys_in_order() {
    let dir = tempfile::tempdir().unwrap();
    let project = project(dir.path(), brief());
    let output = cli(&["brief", path_arg(&project)]);
    assert_eq!(code(&output), 0, "{}", stderr(&output));
    let text = stdout(&output);
    in_order(
        &text,
        &[
            "format",
            "version",
            "brief",
            "observed",
            "entries",
            "lore",
            "suggestions",
        ],
    );
    let json: serde_json::Value = serde_json::from_str(&text).expect("valid JSON");
    assert_eq!(json["format"], "cuboid-brief");
    assert_eq!(json["version"], 1);
    assert_eq!(json["brief"]["project_name"], "Ink Wars");
    assert_eq!(json["brief"]["naming"]["case"], "snake");
    assert_eq!(json["brief"]["texture_size"], 32);
    assert_eq!(json["observed"]["models"], 1);
    assert_eq!(json["observed"]["textures"], 1);
    let kinds: Vec<&str> = json["entries"]
        .as_array()
        .expect("entries")
        .iter()
        .filter_map(|e| e["kind"].as_str())
        .collect();
    assert_eq!(kinds, ["model", "texture", "lore"]);
    assert_eq!(json["lore"][0]["names"][0], "Gun");
    assert_eq!(json["suggestions"][0]["kind"], "lore_without_model");
    // The keys of an entry follow the documented order.
    let entry = &text[text.find("\"entries\"").unwrap()..];
    let (id, kind, name, file, tags, meta) = (
        entry.find("\"id\"").unwrap(),
        entry.find("\"kind\"").unwrap(),
        entry.find("\"name\"").unwrap(),
        entry.find("\"file\"").unwrap(),
        entry.find("\"tags\"").unwrap(),
        entry.find("\"meta\"").unwrap(),
    );
    assert!(id < kind && kind < name && name < file && file < tags && tags < meta);
    // The stored copy is named relative to the library root, ready for `check`.
    let stored = json["entries"][0]["file"].as_str().expect("file");
    assert!(stored.starts_with("files/"), "{stored}");
    // `--json` says the same as nothing.
    let explicit = cli(&["brief", "--json", path_arg(&project)]);
    assert_eq!(stdout(&explicit), text);
}

#[test]
fn a_project_folder_and_a_library_root_give_the_same_brief() {
    let dir = tempfile::tempdir().unwrap();
    let project = project(dir.path(), brief());
    let root = project.join(PROJECT_DIR);
    let from_project = cli(&["brief", "--md", path_arg(&project)]);
    let from_root = cli(&["brief", "--md", path_arg(&root)]);
    assert_eq!(code(&from_project), 0, "{}", stderr(&from_project));
    assert_eq!(stdout(&from_project), stdout(&from_root));
    // The default folder is the current one.
    let here = cli_in(&project, &["brief", "--md"]);
    assert_eq!(stdout(&here), stdout(&from_project));
}

#[test]
fn markdown_is_the_text_of_the_library_function() {
    let dir = tempfile::tempdir().unwrap();
    let project = project(dir.path(), brief());
    let output = cli(&["brief", "--md", path_arg(&project)]);
    assert_eq!(code(&output), 0, "{}", stderr(&output));
    let text = stdout(&output);
    let library =
        Library::read(&project.join(PROJECT_DIR), Scope::Project).expect("the library reads");
    assert_eq!(text, library.brief_markdown());
    assert!(
        text.starts_with("<!-- Generated by cuboid."),
        "the first line says it is generated"
    );
    for part in [
        "# Ink Wars",
        "| Namespace | splatcraft |",
        "| Texel density | 16 texels per block |",
        "| Texture size | 32 px at most |",
        "- Keep it blocky",
        "### Lore",
        "| The Ink Wars | Gun | no |",
    ] {
        assert!(text.contains(part), "{part}\n{text}");
    }
}

#[test]
fn write_puts_brief_md_next_to_the_index_and_prints_its_path() {
    let dir = tempfile::tempdir().unwrap();
    let project = project(dir.path(), brief());
    let root = project.join(PROJECT_DIR);
    let before = names(&root);
    assert!(!before.contains(&BRIEF_FILE.to_owned()));

    let output = cli(&["brief", "--write", path_arg(&project)]);
    assert_eq!(code(&output), 0, "{}", stderr(&output));
    let written = root.join(BRIEF_FILE);
    assert_eq!(stdout(&output).trim(), written.display().to_string());
    let text = fs::read_to_string(&written).expect("brief.md");
    let md = cli(&["brief", "--md", path_arg(&project)]);
    assert_eq!(text, stdout(&md));

    // Only brief.md is new, and a second run leaves it alone.
    let mut expected = before.clone();
    expected.push(BRIEF_FILE.to_owned());
    expected.sort();
    assert_eq!(names(&root), expected);
    let modified = fs::metadata(&written).unwrap().modified().unwrap();
    let again = cli(&["brief", "--write", path_arg(&root)]);
    assert_eq!(code(&again), 0, "{}", stderr(&again));
    assert_eq!(
        fs::metadata(&written).unwrap().modified().unwrap(),
        modified,
        "an unchanged brief.md is not written again"
    );
}

#[test]
fn json_and_markdown_write_nothing() {
    let dir = tempfile::tempdir().unwrap();
    let project = project(dir.path(), brief());
    let root = project.join(PROJECT_DIR);
    let index = fs::read(root.join(INDEX_FILE)).unwrap();
    let before = names(&root);
    for args in [["brief", "--json"], ["brief", "--md"]] {
        let mut full = args.to_vec();
        full.push(path_arg(&project));
        assert_eq!(code(&cli(&full)), 0);
    }
    assert_eq!(names(&root), before);
    assert_eq!(fs::read(root.join(INDEX_FILE)).unwrap(), index);
}

#[test]
fn a_folder_without_an_index_is_an_error_and_a_broken_index_stays_put() {
    let dir = tempfile::tempdir().unwrap();
    let output = cli(&["brief", path_arg(dir.path())]);
    assert_eq!(code(&output), 2);
    assert!(stderr(&output).contains(INDEX_FILE), "{}", stderr(&output));
    assert!(stdout(&output).is_empty());
    assert!(names(dir.path()).is_empty(), "nothing was created");

    fs::write(dir.path().join(INDEX_FILE), b"{ not json").unwrap();
    let output = cli(&["brief", "--write", path_arg(dir.path())]);
    assert_eq!(code(&output), 2);
    assert_eq!(names(dir.path()), [INDEX_FILE], "no .bad copy, no brief.md");

    fs::write(dir.path().join(INDEX_FILE), br#"{"version": 9}"#).unwrap();
    let output = cli(&["brief", path_arg(dir.path())]);
    assert_eq!(code(&output), 2);
    assert!(stderr(&output).contains("newer"), "{}", stderr(&output));
}

#[test]
fn a_schema_1_index_reads_with_the_new_fields_at_their_defaults() {
    let dir = tempfile::tempdir().unwrap();
    fs::write(
        dir.path().join(INDEX_FILE),
        r#"{"version": 1, "brief": {"project_name": "Old", "mc_version": "1.21.6",
            "style_tags": ["pixel"]}, "entries": []}"#,
    )
    .unwrap();
    let output = cli(&["brief", path_arg(dir.path())]);
    assert_eq!(code(&output), 0, "{}", stderr(&output));
    let json: serde_json::Value = serde_json::from_str(&stdout(&output)).unwrap();
    assert_eq!(json["brief"]["project_name"], "Old");
    assert_eq!(json["brief"]["platform"], "vanilla");
    assert_eq!(json["brief"]["texel_density"], serde_json::Value::Null);
    assert_eq!(json["brief"]["palette"], serde_json::json!([]));
    // The file itself is not rewritten as schema 2.
    let text = fs::read_to_string(dir.path().join(INDEX_FILE)).unwrap();
    assert!(text.contains("\"version\": 1"));
}

#[test]
fn bad_command_lines_are_usage_errors() {
    let dir = tempfile::tempdir().unwrap();
    let folder = path_arg(dir.path());
    for args in [
        vec!["brief", "--json", "--md", folder],
        vec!["brief", "--write", "--json", folder],
        vec!["brief", "--write", "--md", folder],
        vec!["brief", folder, folder],
        vec!["brief", "--nope", folder],
    ] {
        let output = cli(&args);
        assert_eq!(code(&output), 1, "{args:?}: {}", stderr(&output));
    }
}
