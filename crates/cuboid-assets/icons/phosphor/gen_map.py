"""Writes src/phosphor_map.rs from the style.css of the @phosphor-icons/web package.

Run it from a folder that holds nothing else, in isolated mode:
    python -I gen_map.py <path to src/regular/style.css> <path to phosphor_map.rs>
"""

import re
import sys

BACKSLASH = chr(92)
css = open(sys.argv[1], encoding="utf-8").read()
pattern = re.compile(
    r"\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*\"" + re.escape(BACKSLASH) + r"([0-9a-f]+)\";"
)
entries = sorted((name, int(code, 16)) for name, code in pattern.findall(css))
names = [name for name, _ in entries]
assert len(set(names)) == len(names), "duplicate icon name"
assert all(0xE000 <= code <= 0xF8FF for _, code in entries), "codepoint outside the private use area"

lines = [
    "//! Codepoints of the Phosphor Regular font, generated by `icons/phosphor/gen_map.py` from the",
    "//! `style.css` of @phosphor-icons/web (see THIRD_PARTY.md). Sorted by name. Do not edit.",
    "",
    "/// Icon name and private-use codepoint.",
    "pub(crate) static PHOSPHOR_MAP: [(&str, u32); %d] = [" % len(entries),
]
lines += ['    ("%s", 0x%04X),' % entry for entry in entries]
lines.append("];")
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
    out.write("\n".join(lines) + "\n")
print(len(entries), "icons")
