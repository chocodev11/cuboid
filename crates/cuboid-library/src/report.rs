//! The brief as an agent reads it: one JSON object and one Markdown text, both computed from
//! the brief and the entries alone, so the same library always gives the same text. The app
//! writes the Markdown as `brief.md` next to the index; `cuboid-cli brief` prints either.

use std::borrow::Cow;
use std::collections::HashSet;
use std::fmt::Write as _;
use std::fs;
use std::io::{self, Read};

use cuboid_assets::mc_versions::{McVersion, mc_versions};
use serde::Serialize;
use serde_json::ser::{Formatter, PrettyFormatter};

use crate::brief::{
    Brief, BriefView, NameCase, StyleSource, Suggestion, brief_view, normalise, suggestions,
};
use crate::kind::{Kind, Role};
use crate::meta::{Meta, ModelMeta};
use crate::store::{Entry, FILES_DIR, Library, LibraryError};
use crate::style::{StyleSummary, style_summary, within};

/// Name of the generated Markdown next to the index.
pub const BRIEF_FILE: &str = "brief.md";
/// Version of the JSON output. Version 2 added the role of an entry and the keys `style` and
/// `style_sources`; a reader of version 1 loses nothing.
pub const JSON_VERSION: u32 = 2;
/// Rows a table of the Markdown lists; the JSON lists every entry.
const MD_ROWS: usize = 200;
/// Style references the Markdown lists.
const MD_STYLE_ROWS: usize = 30;
const NOT_SET: &str = "not set";
const GENERATED: &str = "<!-- Generated by cuboid. The brief is edited in cuboid; changes to this file are overwritten. -->";

#[derive(Serialize)]
struct Report<'a> {
    format: &'static str,
    version: u32,
    brief: &'a Brief,
    observed: Observed<'a>,
    style_sources: &'a [StyleSource],
    style: Option<StyleSummary>,
    entries: Vec<EntryJson<'a>>,
    lore: Vec<LoreJson<'a>>,
    suggestions: Vec<SuggestionJson<'a>>,
}

#[derive(Serialize)]
struct Observed<'a> {
    palette: &'a [[u8; 3]],
    texel_density: Option<f32>,
    models: usize,
    textures: usize,
}

#[derive(Serialize)]
struct EntryJson<'a> {
    id: &'a str,
    kind: Kind,
    role: Role,
    name: &'a str,
    /// The stored copy relative to the library root, for `cuboid-cli check`.
    file: String,
    tags: &'a [String],
    meta: Option<Cow<'a, Meta>>,
}

/// The metadata of an entry as the JSON lists it: a model without its `style`, which the summary
/// sums up and `refs_get` gives per model. About 1 KB of pretty JSON a reference stays out.
fn listed(meta: &Meta) -> Cow<'_, Meta> {
    match meta {
        Meta::Model(model) if model.style.is_some() => Cow::Owned(Meta::Model(ModelMeta {
            format: model.format.clone(),
            style: None,
            ..*model
        })),
        _ => Cow::Borrowed(meta),
    }
}

#[derive(Serialize)]
struct LoreJson<'a> {
    entry: &'a str,
    title: &'a str,
    names: &'a [String],
}

#[derive(Serialize)]
struct SuggestionJson<'a> {
    kind: &'static str,
    entry: &'a str,
    title: &'a str,
    detail: &'a str,
}

/// Where the writer is, so that the arrays inside arrays (the colours) stay on one line.
enum Open {
    Object,
    Array,
    Inline,
}

/// Pretty printing, except that an array inside an array is written on one line: `[200, 20, 20]`.
struct Tidy {
    pretty: PrettyFormatter<'static>,
    open: Vec<Open>,
}

impl Default for Tidy {
    fn default() -> Self {
        Tidy {
            pretty: PrettyFormatter::new(),
            open: Vec::new(),
        }
    }
}

impl Formatter for Tidy {
    fn begin_array<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        let inline = matches!(self.open.last(), Some(Open::Array));
        self.open
            .push(if inline { Open::Inline } else { Open::Array });
        if inline {
            writer.write_all(b"[")
        } else {
            self.pretty.begin_array(writer)
        }
    }

    fn end_array<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        if matches!(self.open.pop(), Some(Open::Inline)) {
            writer.write_all(b"]")
        } else {
            self.pretty.end_array(writer)
        }
    }

    fn begin_array_value<W: ?Sized + io::Write>(
        &mut self,
        writer: &mut W,
        first: bool,
    ) -> io::Result<()> {
        match (self.open.last(), first) {
            (Some(Open::Inline), true) => Ok(()),
            (Some(Open::Inline), false) => writer.write_all(b", "),
            _ => self.pretty.begin_array_value(writer, first),
        }
    }

    fn end_array_value<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        match self.open.last() {
            Some(Open::Inline) => Ok(()),
            _ => self.pretty.end_array_value(writer),
        }
    }

    fn begin_object<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        self.open.push(Open::Object);
        self.pretty.begin_object(writer)
    }

    fn end_object<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        self.open.pop();
        self.pretty.end_object(writer)
    }

    fn begin_object_key<W: ?Sized + io::Write>(
        &mut self,
        writer: &mut W,
        first: bool,
    ) -> io::Result<()> {
        self.pretty.begin_object_key(writer, first)
    }

    fn begin_object_value<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        self.pretty.begin_object_value(writer)
    }

    fn end_object_value<W: ?Sized + io::Write>(&mut self, writer: &mut W) -> io::Result<()> {
        self.pretty.end_object_value(writer)
    }
}

/// The entries in the order the reports list them: by kind, then by name, then by id.
fn ordered(entries: &[Entry]) -> Vec<&Entry> {
    let mut list: Vec<&Entry> = entries.iter().collect();
    list.sort_by_cached_key(|e| (e.kind.index(), e.name.to_lowercase(), e.id.clone()));
    list
}

impl Library {
    /// The brief, the observed values, the entries, the lore and the suggestions as one JSON
    /// object (`cuboid-brief`, version [`JSON_VERSION`]) with its keys in a fixed order. A lore
    /// note without a heading is titled with its file name. The `meta` of a model leaves out its
    /// `style`: the key `style` sums it up for all references and the index keeps it per model.
    pub fn brief_json(&self) -> Result<String, LibraryError> {
        let entries = self.entries();
        let mut view = brief_view(self.brief(), entries);
        // The sources have a key of their own.
        let sources = std::mem::take(&mut view.brief.style_sources);
        let hints = suggestions(self.brief(), entries);
        let ordered = ordered(entries);
        let report = Report {
            format: "cuboid-brief",
            version: JSON_VERSION,
            brief: &view.brief,
            observed: Observed {
                palette: &view.palette,
                texel_density: view.density,
                models: view.models,
                textures: view.textures,
            },
            style_sources: &sources,
            style: style_summary(entries),
            entries: ordered
                .iter()
                .map(|e| EntryJson {
                    id: &e.id,
                    kind: e.kind,
                    role: e.role,
                    name: &e.name,
                    file: format!("{FILES_DIR}/{}", e.file),
                    tags: &e.tags,
                    meta: e.meta.as_ref().map(listed),
                })
                .collect(),
            lore: ordered
                .iter()
                .filter_map(|e| match &e.meta {
                    Some(Meta::Lore(lore)) => Some(LoreJson {
                        entry: &e.id,
                        title: lore.title.as_deref().unwrap_or(&e.name),
                        names: &lore.names,
                    }),
                    _ => None,
                })
                .collect(),
            suggestions: hints
                .iter()
                .map(|s| SuggestionJson {
                    kind: s.kind.name(),
                    entry: &s.entry,
                    title: &s.title,
                    detail: &s.detail,
                })
                .collect(),
        };
        let mut bytes = Vec::new();
        report.serialize(&mut serde_json::Serializer::with_formatter(
            &mut bytes,
            Tidy::default(),
        ))?;
        Ok(String::from_utf8_lossy(&bytes).into_owned())
    }

    /// The same view as Markdown for language models: the project, the targets, the rules, the
    /// style references, what the library holds and the suggestions, in short tables.
    pub fn brief_markdown(&self) -> String {
        let entries = self.entries();
        let view = brief_view(self.brief(), entries);
        let hints = suggestions(self.brief(), entries);
        let mut out = String::new();
        let _ = writeln!(out, "{GENERATED}\n");
        let title = match view.brief.project_name.as_str() {
            "" => "Untitled project",
            name => name,
        };
        let _ = writeln!(out, "# {}\n", cell(title));
        project_section(&mut out, self, &view);
        targets_section(&mut out, &view);
        rules_section(&mut out, &view);
        let ordered = ordered(entries);
        style_section(
            &mut out,
            &view.brief.style_sources,
            style_summary(entries).as_ref(),
            &ordered,
        );
        library_section(&mut out, &view, &ordered);
        suggestions_section(&mut out, &hints);
        out
    }

    /// Writes `brief.md` next to the index, atomically, and only when the text differs from the
    /// file. Returns whether it wrote. The folder must exist.
    pub fn write_brief_md(&self) -> Result<bool, LibraryError> {
        let path = self.root().join(BRIEF_FILE);
        let text = self.brief_markdown();
        if holds(&path, text.as_bytes()) {
            return Ok(false);
        }
        cuboid_io::write_atomic(&path, text.as_bytes())?;
        Ok(true)
    }
}

/// Whether the file holds exactly these bytes. A file of another size is not read.
fn holds(path: &std::path::Path, text: &[u8]) -> bool {
    let Ok(file) = fs::File::open(path) else {
        return false;
    };
    let size = text.len() as u64;
    if file.metadata().is_ok_and(|meta| meta.len() != size) {
        return false;
    }
    let mut old = Vec::with_capacity(text.len());
    file.take(size + 1).read_to_end(&mut old).is_ok() && old == text
}

/// Text for a table cell: no pipes, no line breaks.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', "<br>")
}

fn color_hex(color: &[u8; 3]) -> String {
    format!("#{:02x}{:02x}{:02x}", color[0], color[1], color[2])
}

fn colors(list: &[[u8; 3]]) -> String {
    let codes: Vec<String> = list.iter().map(color_hex).collect();
    codes.join(" ")
}

/// `16` for 16.0 and `21.3` for 21.33.
fn number(value: f32) -> String {
    let text = format!("{value:.1}");
    match text.strip_suffix(".0") {
        Some(whole) => whole.to_owned(),
        None => text,
    }
}

fn or_not_set(text: &str) -> String {
    if text.is_empty() {
        NOT_SET.to_owned()
    } else {
        cell(text)
    }
}

/// The pack format of a game version, `None` when the table has none or the text is no version.
fn pack_format(version: &str) -> Option<String> {
    let entry = mc_versions().pack_format_for(McVersion::parse(version)?)?;
    let format = entry.format;
    Some(if format.minor == 0 {
        format.major.to_string()
    } else {
        format!("{}.{}", format.major, format.minor)
    })
}

/// A table; rows beyond [`MD_ROWS`] are counted in a line below it.
fn table(out: &mut String, header: &[&str], rows: &[Vec<String>]) {
    let _ = writeln!(out, "| {} |", header.join(" | "));
    let _ = writeln!(out, "|{}", "---|".repeat(header.len()));
    for row in rows.iter().take(MD_ROWS) {
        let _ = writeln!(out, "| {} |", row.join(" | "));
    }
    if rows.len() > MD_ROWS {
        let _ = writeln!(
            out,
            "\n{} more are in `cuboid-cli brief --json`.",
            rows.len() - MD_ROWS
        );
    }
    out.push('\n');
}

fn pairs(out: &mut String, header: [&str; 2], rows: Vec<(&str, String)>) {
    let rows: Vec<Vec<String>> = rows
        .into_iter()
        .map(|(name, value)| vec![name.to_owned(), value])
        .collect();
    table(out, &header, &rows);
}

fn project_section(out: &mut String, library: &Library, view: &BriefView) {
    let brief = &view.brief;
    let version = if library.brief().mc_version.is_empty() {
        format!("{} (newest known; not set)", brief.mc_version)
    } else {
        brief.mc_version.clone()
    };
    let style = brief.style_tags.join(", ");
    out.push_str("## Project\n\n");
    pairs(
        out,
        ["Field", "Value"],
        vec![
            ("Name", or_not_set(&brief.project_name)),
            ("Goal", or_not_set(&brief.goal)),
            ("Platform", brief.platform.id().to_owned()),
            ("Namespace", or_not_set(&brief.namespace)),
            ("Game version", cell(&version)),
            (
                "Pack format",
                pack_format(&brief.mc_version).unwrap_or_else(|| "unknown".to_owned()),
            ),
            ("Style", or_not_set(&style)),
        ],
    );
}

fn targets_section(out: &mut String, view: &BriefView) {
    let brief = &view.brief;
    let density = brief.texel_density.map_or_else(
        || NOT_SET.to_owned(),
        |d| format!("{} texels per block", number(d)),
    );
    let size = brief
        .texture_size
        .map_or_else(|| NOT_SET.to_owned(), |s| format!("{s} px at most"));
    let palette = if brief.palette.is_empty() {
        NOT_SET.to_owned()
    } else if brief.palette_strict {
        format!(
            "{} (strict: other colours are errors)",
            colors(&brief.palette)
        )
    } else {
        format!("{} (other colours are warnings)", colors(&brief.palette))
    };
    let budget = brief
        .max_elements
        .map_or_else(|| NOT_SET.to_owned(), |n| format!("{n} elements per model"));
    let mut naming = Vec::new();
    match brief.naming.case {
        NameCase::Snake => naming.push("snake_case".to_owned()),
        NameCase::Kebab => naming.push("kebab-case".to_owned()),
        NameCase::Any => {}
    }
    if !brief.naming.prefix.is_empty() {
        naming.push(format!("prefix \"{}\"", brief.naming.prefix));
    }
    let naming = if naming.is_empty() {
        NOT_SET.to_owned()
    } else {
        cell(&naming.join(", "))
    };
    let display = brief
        .display_preset
        .map_or_else(|| NOT_SET.to_owned(), |p| p.id().to_owned());
    out.push_str("## Targets\n\n");
    pairs(
        out,
        ["Target", "Value"],
        vec![
            ("Texel density", density),
            ("Texture size", size),
            ("Palette", palette),
            ("Element budget", budget),
            ("Naming", naming),
            ("Display preset", display),
        ],
    );
}

fn rules_section(out: &mut String, view: &BriefView) {
    out.push_str("## Rules\n\n");
    if view.brief.rules.is_empty() {
        out.push_str("(none)\n\n");
        return;
    }
    for rule in &view.brief.rules {
        let _ = writeln!(out, "- {rule}");
    }
    out.push('\n');
}

/// The cells of a model row: name, format, elements, texel density and texture size.
fn model_cells(entry: &Entry) -> Vec<String> {
    let dash = || "-".to_owned();
    match &entry.meta {
        Some(Meta::Model(m)) => vec![
            cell(&entry.name),
            cell(&m.format),
            m.elements.to_string(),
            m.density.map_or_else(dash, number),
            m.texture_size.map_or_else(dash, |s| s.to_string()),
        ],
        _ => vec![cell(&entry.name), dash(), dash(), dash(), dash()],
    }
}

/// The folders, the summary and the first references of the style references.
fn style_section(
    out: &mut String,
    sources: &[StyleSource],
    summary: Option<&StyleSummary>,
    entries: &[&Entry],
) {
    out.push_str("## Style references\n\n");
    if sources.is_empty() && summary.is_none() {
        out.push_str("(none)\n\n");
        return;
    }
    let style = || {
        entries
            .iter()
            .copied()
            .filter(|entry| entry.role == Role::Style)
    };
    if !sources.is_empty() {
        let from = |source: &StyleSource, kind: Kind| {
            let count = style()
                .filter(|entry| entry.kind == kind && within(&entry.source, &source.path))
                .count();
            let word = if count == 1 {
                kind.name()
            } else {
                kind.plural()
            };
            format!("{count} {word}")
        };
        let rows: Vec<Vec<String>> = sources
            .iter()
            .map(|source| {
                vec![
                    cell(&source.path),
                    cell(&source.licence),
                    or_not_set(&source.tags.join(", ")),
                    format!(
                        "{}, {}",
                        from(source, Kind::Model),
                        from(source, Kind::Texture)
                    ),
                ]
            })
            .collect();
        out.push_str("### Folders\n\n");
        table(out, &["Folder", "Licence", "Tags", "References"], &rows);
    }
    let Some(summary) = summary else {
        return;
    };
    out.push_str("### Summary\n\n");
    pairs(out, ["Property", "Value"], style_rows(summary, entries));

    // The typical references come first, then the others by name.
    let (mut first, rest): (Vec<&Entry>, Vec<&Entry>) = style()
        .filter(|entry| entry.kind == Kind::Model)
        .partition(|entry| summary.typical.contains(&entry.id));
    first.sort_by_key(|entry| summary.typical.iter().position(|id| *id == entry.id));
    let mut rows: Vec<Vec<String>> = first
        .into_iter()
        .chain(rest)
        .map(|entry| {
            let display = match &entry.meta {
                Some(Meta::Model(m)) => m.style.as_ref().and_then(|s| s.display.clone()),
                _ => None,
            };
            let mut cells = vec![entry.id.clone()];
            cells.extend(model_cells(entry));
            cells.push(display.unwrap_or_else(|| "-".to_owned()));
            cells
        })
        .collect();
    if rows.is_empty() {
        return;
    }
    out.push_str("### References\n\n");
    if rows.len() > MD_STYLE_ROWS {
        let _ = writeln!(
            out,
            "The first {MD_STYLE_ROWS} of {} are listed; `cuboid-cli brief --json` lists all.\n",
            rows.len()
        );
        rows.truncate(MD_STYLE_ROWS);
    }
    let header = [
        "Id",
        "Name",
        "Format",
        "Elements",
        "Texel density",
        "Texture size",
        "Display",
    ];
    table(out, &header, &rows);
}

/// The summary as the rows of a table.
fn style_rows(summary: &StyleSummary, entries: &[&Entry]) -> Vec<(&'static str, String)> {
    let mut rows = vec![
        ("Models", summary.models.to_string()),
        ("Textures", summary.textures.to_string()),
    ];
    if let Some(elements) = &summary.elements {
        rows.push((
            "Elements per model",
            format!(
                "{} to {}, median {}",
                number(elements.min),
                number(elements.max),
                number(elements.median)
            ),
        ));
    }
    if let Some(size) = &summary.element_size {
        rows.push((
            "Element size",
            format!(
                "longest side in px: 10th percentile {}, median {}, 90th percentile {}; {}% of the elements are 1 px or thinner",
                number(size.p10),
                number(size.median),
                number(size.p90),
                number(size.thin_share * 100.0)
            ),
        ));
    }
    if let Some(groups) = &summary.groups {
        rows.push((
            "Groups per model",
            format!(
                "median {}, depth {}",
                number(groups.median),
                number(groups.depth)
            ),
        ));
    }
    if let Some(density) = &summary.texel_density {
        rows.push((
            "Texel density",
            format!(
                "10th percentile {}, median {}, 90th percentile {}; {}% of the models are near the median",
                number(density.p10),
                number(density.median),
                number(density.p90),
                number(density.near_median_share * 100.0)
            ),
        ));
    }
    let sizes: Vec<String> = summary
        .texture_sizes
        .iter()
        .map(|(size, count)| format!("{size} px: {count}"))
        .collect();
    rows.push(("Texture sizes", or_none(sizes.join(", "))));
    rows.push(("Palette", or_none(summary.palette.join(" "))));
    if let Some(rotation) = &summary.rotation {
        let angles: Vec<String> = rotation.angles.iter().map(|a| number(*a)).collect();
        rows.push((
            "Rotation",
            format!(
                "{}% of the elements; angles {}",
                number(rotation.share * 100.0),
                or_none(angles.join(", "))
            ),
        ));
    }
    if let Some(naming) = &summary.naming {
        let case = match naming.case {
            NameCase::Snake => "snake_case",
            NameCase::Kebab => "kebab-case",
            NameCase::Any => "mixed",
        };
        rows.push((
            "Naming",
            format!("{case}; words {}", or_none(naming.tokens.join(", "))),
        ));
    }
    let presets: Vec<String> = summary
        .display
        .iter()
        .map(|(preset, count)| format!("{preset}: {count}"))
        .collect();
    rows.push(("Display", or_none(presets.join(", "))));
    let typical: Vec<String> = summary
        .typical
        .iter()
        .map(|id| {
            let name = entries
                .iter()
                .find(|entry| entry.id == *id)
                .map(|e| &*e.name);
            format!("{} ({id})", cell(name.unwrap_or("?")))
        })
        .collect();
    rows.push(("Typical", or_none(typical.join(", "))));
    rows
}

fn or_none(text: String) -> String {
    if text.is_empty() {
        "none".to_owned()
    } else {
        text
    }
}

fn library_section(out: &mut String, view: &BriefView, entries: &[&Entry]) {
    out.push_str("## Library\n\n");
    let _ = writeln!(out, "- Models: {}", view.models);
    let _ = writeln!(out, "- Textures: {}", view.textures);
    let _ = writeln!(
        out,
        "- Observed texel density: {}",
        view.density.map_or_else(
            || "none".to_owned(),
            |d| format!("{} texels per block", number(d))
        )
    );
    let _ = writeln!(
        out,
        "- Observed palette: {}\n",
        if view.palette.is_empty() {
            "none".to_owned()
        } else {
            colors(&view.palette)
        }
    );

    let of_kind = |kind: Kind| {
        entries
            .iter()
            .copied()
            .filter(move |e| e.kind == kind && e.role == Role::Work)
    };
    let models: Vec<Vec<String>> = of_kind(Kind::Model).map(model_cells).collect();
    if !models.is_empty() {
        out.push_str("### Models\n\n");
        table(
            out,
            &[
                "Name",
                "Format",
                "Elements",
                "Texel density",
                "Texture size",
            ],
            &models,
        );
    }

    let textures: Vec<Vec<String>> = of_kind(Kind::Texture)
        .map(|e| match &e.meta {
            Some(Meta::Texture(t)) => vec![
                cell(&e.name),
                format!("{} x {}", t.width, t.height),
                t.frames.to_string(),
                t.alpha.map_or("-", |a| a.name()).to_owned(),
            ],
            _ => vec![
                cell(&e.name),
                "-".to_owned(),
                "-".to_owned(),
                "-".to_owned(),
            ],
        })
        .collect();
    if !textures.is_empty() {
        out.push_str("### Textures\n\n");
        table(out, &["Name", "Size", "Frames", "Alpha"], &textures);
    }

    let references: Vec<&Entry> = of_kind(Kind::Reference).collect();
    if !references.is_empty() {
        out.push_str("### References\n\n");
        for entry in references.iter().take(MD_ROWS) {
            let _ = writeln!(out, "- {}", entry.name);
        }
        if references.len() > MD_ROWS {
            let _ = writeln!(
                out,
                "\n{} more are in `cuboid-cli brief --json`.",
                references.len() - MD_ROWS
            );
        }
        out.push('\n');
    }

    let models: HashSet<String> = of_kind(Kind::Model).map(|e| normalise(e.stem())).collect();
    let mut lore: Vec<Vec<String>> = Vec::new();
    for entry in of_kind(Kind::Lore) {
        let Some(Meta::Lore(note)) = &entry.meta else {
            continue;
        };
        let title = cell(note.title.as_deref().unwrap_or(&entry.name));
        if note.names.is_empty() {
            lore.push(vec![title, "-".to_owned(), "-".to_owned()]);
            continue;
        }
        for name in &note.names {
            let exists = models.contains(&normalise(name));
            lore.push(vec![
                title.clone(),
                cell(name),
                if exists { "yes" } else { "no" }.to_owned(),
            ]);
        }
    }
    if !lore.is_empty() {
        out.push_str("### Lore\n\n");
        table(out, &["Note", "Name", "Model"], &lore);
    }
}

fn suggestions_section(out: &mut String, hints: &[Suggestion]) {
    out.push_str("## Suggestions\n\n");
    if hints.is_empty() {
        out.push_str("(none)\n");
        return;
    }
    for hint in hints {
        let _ = writeln!(out, "- {}: {}", hint.title, hint.detail);
    }
}

